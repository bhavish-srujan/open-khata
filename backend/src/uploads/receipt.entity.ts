import {
  Entity,
  Column,
  PrimaryGeneratedColumn,
  CreateDateColumn,
  ManyToOne,
  JoinColumn,
} from 'typeorm';
import { Business } from '../business/business.entity';

/**
 * Ownership record for an uploaded receipt.
 *
 * Receipts previously had no association to anything: the file was written to
 * disk under a random name and served by a static handler with no auth, so
 * anyone holding a URL could read another business's financial document. This
 * row is what makes an authorization decision possible.
 *
 * The public URL carries this row's id rather than the on-disk filename, so the
 * client never supplies a path and directory traversal is not reachable.
 */
@Entity('receipts')
export class Receipt {
  @PrimaryGeneratedColumn('uuid')
  id: string;

  @Column({ name: 'business_id' })
  businessId: string;

  @ManyToOne(() => Business)
  @JoinColumn({ name: 'business_id' })
  business: Business;

  /** User id from the JWT at upload time, for audit purposes. */
  @Column({ name: 'uploaded_by' })
  uploadedBy: string;

  /** Name on disk, generated by multer. Never accepted from the client. */
  @Column()
  filename: string;

  @Column({ name: 'mime_type' })
  mimeType: string;

  @Column({ name: 'size_bytes', type: 'int' })
  sizeBytes: number;

  @CreateDateColumn({ name: 'created_at' })
  createdAt: Date;
}
